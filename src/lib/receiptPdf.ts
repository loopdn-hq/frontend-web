// A payment receipt as a PDF file, written here rather than by a library: it
// is one page of text, and that is a few dozen lines of the format.
//
// This is the app's own record of a payment. Stripe's hosted receipt, linked
// from it, remains the official one.

import {
  formatTransactionAmount,
  receiptHref,
  type BillingTransaction,
} from "@/lib/billingTransactions";

const APP_NAME = "Loopd'n";

// A4, in points.
const PAGE_WIDTH = 595;
const PAGE_HEIGHT = 842;
const MARGIN = 56;
const VALUE_X = 190;
// What fits between VALUE_X and the right margin at 11pt Helvetica.
const VALUE_WIDTH_CHARS = 58;

// The standard fonts are single-byte (WinAnsi). These are the characters
// outside Latin-1 it has a place for that a receipt is likely to carry.
const WIN_ANSI: Record<string, number> = {
  "€": 0x80,
  "‘": 0x91,
  "’": 0x92,
  "“": 0x93,
  "”": 0x94,
  "•": 0x95,
  "–": 0x96,
  "—": 0x97,
};

/** A string as the body of a PDF literal: one byte a character, escaped. */
function pdfText(value: string): string {
  let out = "";
  for (const char of value) {
    const code = char.codePointAt(0) ?? 0x3f;
    let byte = 0x3f; // "?" for anything the font cannot draw
    if (WIN_ANSI[char] !== undefined) {
      byte = WIN_ANSI[char];
    } else if (code === 0xa0 || code === 0x2009 || code === 0x202f) {
      // The spaces Intl puts inside dates and amounts.
      byte = 0x20;
    } else if (
      (code >= 0x20 && code <= 0x7e) ||
      (code >= 0xa1 && code <= 0xff)
    ) {
      byte = code;
    }

    const literal = String.fromCharCode(byte);
    out +=
      literal === "(" || literal === ")" || literal === "\\"
        ? `\\${literal}`
        : literal;
  }
  return out;
}

/** Broken on spaces where there are any, and mid-word where there are not. */
function wrap(value: string, width: number): string[] {
  const lines: string[] = [];
  let line = "";
  for (const word of value.split(/\s+/).filter(Boolean)) {
    let rest = word;
    while (rest.length > width) {
      if (line) {
        lines.push(line);
        line = "";
      }
      lines.push(rest.slice(0, width));
      rest = rest.slice(width);
    }
    if (line && line.length + 1 + rest.length > width) {
      lines.push(line);
      line = rest;
    } else {
      line = line ? `${line} ${rest}` : rest;
    }
  }
  if (line) lines.push(line);
  return lines;
}

function formatPaidAt(value: string, locale?: string): string {
  const date = new Date(value);
  return Number.isNaN(date.getTime())
    ? ""
    : date.toLocaleString(locale, {
        month: "short",
        day: "numeric",
        year: "numeric",
        hour: "numeric",
        minute: "2-digit",
        timeZoneName: "short",
      });
}

/** The page's drawing instructions. */
function receiptContent(receipt: BillingTransaction, locale?: string): string {
  const ops: string[] = [];
  let y = PAGE_HEIGHT - 72;

  const text = (
    value: string,
    x: number,
    font: "F1" | "F2",
    size: number,
    gray = 0,
  ) => {
    ops.push(
      `${gray} g BT /${font} ${size} Tf ${x} ${y} Td (${pdfText(value)}) Tj ET`,
    );
  };
  const rule = () => {
    ops.push(`0.85 G 0.5 w ${MARGIN} ${y} m ${PAGE_WIDTH - MARGIN} ${y} l S`);
  };

  text(APP_NAME, MARGIN, "F2", 11, 0.4);
  y -= 30;
  text("Payment receipt", MARGIN, "F2", 22);
  y -= 44;
  // The currency as its code, not its symbol: "USD 9.99" is unambiguous on
  // paper, and every code is made of characters the font has.
  text(
    formatTransactionAmount(
      receipt.amountCents,
      receipt.currency,
      locale,
      "code",
    ),
    MARGIN,
    "F2",
    28,
  );
  y -= 28;
  rule();
  y -= 26;

  const rows: [string, string][] = [
    ["Description", receipt.description],
    ["Type", receipt.kindLabel],
    ["Paid", formatPaidAt(receipt.paidAt, locale)],
    ["Receipt no.", String(receipt.id)],
    ["Stripe reference", receipt.stripeReference],
    ["Stripe receipt", receiptHref(receipt.receiptUrl) ?? ""],
  ];
  for (const [label, value] of rows) {
    const lines = wrap(value, VALUE_WIDTH_CHARS);
    if (lines.length === 0) continue;
    text(label, MARGIN, "F1", 10, 0.4);
    for (const line of lines) {
      text(line, VALUE_X, "F1", 11);
      y -= 16;
    }
    y -= 8;
  }

  y -= 2;
  rule();
  y -= 22;
  text(
    `Generated by ${APP_NAME} from your account's payment history.`,
    MARGIN,
    "F1",
    9,
    0.4,
  );
  return ops.join("\n");
}

/**
 * The receipt as the bytes of a one-page PDF.
 *
 * Every character written is a single byte, so a string's length is its byte
 * length - which is what lets the cross-reference table's offsets be counted
 * off the string as it is built.
 */
export function buildReceiptPdf(
  receipt: BillingTransaction,
  locale?: string,
): Uint8Array<ArrayBuffer> {
  const content = receiptContent(receipt, locale);
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_WIDTH} ${PAGE_HEIGHT}] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
  ];

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((body, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xrefAt = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    pdf += `${String(offset).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefAt}\n%%EOF\n`;

  const bytes = new Uint8Array(pdf.length);
  for (let index = 0; index < pdf.length; index += 1) {
    bytes[index] = pdf.charCodeAt(index);
  }
  return bytes;
}

export function receiptFileName(receipt: BillingTransaction): string {
  return `receipt-${receipt.id}.pdf`;
}

/** Hand the receipt to the browser as a file to save. */
export function downloadReceiptPdf(receipt: BillingTransaction): void {
  const url = URL.createObjectURL(
    new Blob([buildReceiptPdf(receipt)], { type: "application/pdf" }),
  );
  const link = document.createElement("a");
  link.href = url;
  link.download = receiptFileName(receipt);
  document.body.appendChild(link);
  link.click();
  link.remove();
  // Not revoked in the same tick: some browsers read the blob after click().
  setTimeout(() => URL.revokeObjectURL(url), 1_000);
}
